import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
const root = new URL("../", import.meta.url),
  out = new URL("supabase/functions/_shared/generated/", root);
mkdirSync(out, { recursive: true });
for (const name of ["model", "schedule", "workspace", "brief", "ical-zone"]) {
  const source = readFileSync(new URL(`lib/${name}.ts`, root), "utf8");
  const hash = createHash("sha256").update(source).digest("hex");
  const converted = source
    .replaceAll('from "zod"', 'from "npm:zod@4.1.5"')
    .replaceAll(
      'from "@js-temporal/polyfill"',
      'from "npm:@js-temporal/polyfill@0.5.1"',
    )
    .replace(/from "\.\/(model|schedule|workspace)"/g, 'from "./$1.ts"');
  writeFileSync(
    new URL(`${name}.ts`, out),
    `// Generated by scripts/build-server-contracts.mjs. Source SHA-256: ${hash}\n${converted}`,
  );
}
